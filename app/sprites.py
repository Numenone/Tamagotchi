"""Pixel art compartilhada entre o simulador do PC e o firmware do Arduino.

Tudo aqui e a "fonte da verdade": o gerador de firmware converte estes
desenhos em bytes (anim_data.h) e o simulador pygame desenha os mesmos
pixels. Assim o pet do PC e o pet do display OLED ficam identicos.

Legenda: '#' = pixel aceso, '.' = apagado.
Um nome terminado em '~' significa "versao espelhada" (gerada automaticamente).
"""

# ---------------------------------------------------------------------------
# Corpo do pet (gerado por formula para ficar bem redondinho)
# ---------------------------------------------------------------------------
BODY_W, BODY_H = 32, 30


def _make_body():
    W, H = BODY_W, BODY_H
    cx, cy, a, b, p = 15.5, 15.5, 15.0, 11.2, 2.6

    def inside(x, y):
        if x < 0 or y < 0 or x >= W or y >= H:
            return False
        X, Y = x + 0.5, y + 0.5
        if abs((X - cx) / a) ** p + abs((Y - cy) / b) ** p <= 1.0:
            return True
        for ex in (8.0, 23.0):  # orelhinhas
            if 0.5 <= Y <= 8.0 and abs(X - ex) <= (Y - 0.5) * 0.5 + 0.7:
                return True
        for fx in (9.5, 21.5):  # pezinhos
            if ((X - fx) / 3.4) ** 2 + ((Y - 27.0) / 2.6) ** 2 <= 1.0:
                return True
        return False

    rows = []
    for y in range(H):
        r = ""
        for x in range(W):
            edge = inside(x, y) and not (
                inside(x - 1, y) and inside(x + 1, y) and inside(x, y - 1) and inside(x, y + 1)
            )
            r += "#" if edge else "."
        rows.append(r)
    # brilho na cabeca e barriguinha pontilhada (charme pixel art)
    rows = [list(r) for r in rows]
    for (x, y) in [(6, 8), (5, 9), (5, 10)]:
        rows[y][x] = "#"
    for (x, y) in [(13, 25), (15, 26), (17, 25)]:
        rows[y][x] = "#"
    return ["".join(r) for r in rows]


BODY = _make_body()

