def mirror(rows):
    return [r[::-1] for r in rows]


def all_sprites():
    """Dicionario nome -> linhas, incluindo corpo e versoes espelhadas pedidas."""
    out = {"body": BODY}
    out.update(EYE_SPRITES)
    out.update(MOUTH_SPRITES)
    out.update(ICON_SPRITES)
    return out


def get_sprite(name):
    base = all_sprites()
    if name.endswith("~"):
        return mirror(base[name[:-1]])
    return base[name]
